/**
 * DoneFlow REST API integration module.
 *
 * The functions in this file intentionally use the browser Fetch API and
 * async/await so the vanilla JavaScript UI can call the FastAPI backend without
 * framework-specific dependencies.
 */

const API_BASE_URL = "/api/v1";

/**
 * Valid Eisenhower Matrix quadrants returned by DoneFlow.
 *
 * @typedef {"DO_NOW" | "SCHEDULE" | "DELEGATE" | "ELIMINATE"} Quadrant
 */

/**
 * Task resource returned by the DoneFlow API.
 *
 * @typedef {Object} Task
 * @property {string} id - UUID that identifies the task.
 * @property {string} description - Human-readable task description.
 * @property {Quadrant} quadrant - Eisenhower Matrix quadrant assigned to the task.
 * @property {number} ai_confidence - AI classification confidence from 0 to 1.
 * @property {string | null} ai_reasoning - Optional AI explanation for the classification.
 * @property {string} created_at - ISO-8601 timestamp when the task was created.
 * @property {string | null} updated_at - ISO-8601 timestamp when the task was last updated.
 */

/**
 * Task distribution counters grouped by quadrant.
 *
 * @typedef {Object} Distribution
 * @property {number} DO_NOW - Number of urgent and important tasks.
 * @property {number} SCHEDULE - Number of important but non-urgent tasks.
 * @property {number} DELEGATE - Number of urgent but less-important tasks.
 * @property {number} ELIMINATE - Number of low-priority tasks.
 * @property {number} total - Total number of tasks across all quadrants.
 */

/**
 * Health-check response returned by the API.
 *
 * @typedef {Object} HealthResponse
 * @property {string} status - Current API health status.
 * @property {string} [version] - Optional application version.
 * @property {string} [timestamp] - Optional ISO-8601 timestamp generated by the API.
 */

/**
 * Error payload shape commonly returned by FastAPI.
 *
 * @typedef {Object} ApiErrorPayload
 * @property {string | Object | Array<Object>} [detail] - API validation or error details.
 * @property {string} [message] - Optional generic API error message.
 */

const DEFAULT_HEADERS = {
  "Accept": "application/json",
  "Content-Type": "application/json",
};

const HTTP_ERROR_MESSAGES = {
  400: "Não foi possível processar a solicitação.",
  404: "Tarefa não encontrada.",
  422: "Revise os dados enviados e tente novamente.",
  500: "Ocorreu um erro interno no DoneFlow.",
};

/**
 * Convert an API error response into a friendly Portuguese message.
 *
 * @param {Response} response - Fetch response with a non-success HTTP status.
 * @param {ApiErrorPayload | null} payload - Parsed API error payload, when available.
 * @returns {string} Friendly error message for the UI.
 */
function buildHttpErrorMessage(response, payload) {
  const fallbackMessage =
    HTTP_ERROR_MESSAGES[response.status] || `Erro inesperado no DoneFlow (HTTP ${response.status}).`;

  if (typeof payload?.detail === "string" && payload.detail.trim() !== "") {
    return `${fallbackMessage} ${payload.detail}`;
  }

  if (typeof payload?.message === "string" && payload.message.trim() !== "") {
    return `${fallbackMessage} ${payload.message}`;
  }

  return fallbackMessage;
}

/**
 * Parse a JSON response if the endpoint returned a response body.
 *
 * @template T
 * @param {Response} response - Fetch response returned by the browser.
 * @returns {Promise<T | undefined>} Parsed JSON body, or undefined for empty responses.
 */
async function parseJsonResponse(response) {
  if (response.status === 204) {
    return undefined;
  }

  const contentType = response.headers.get("content-type") || "";
  if (!contentType.includes("application/json")) {
    return undefined;
  }

  return await response.json();
}

/**
 * Execute a DoneFlow API request and normalize HTTP/network failures.
 *
 * @template T
 * @param {string} url - Absolute or root-relative endpoint URL.
 * @param {RequestInit} [options={}] - Fetch options for method, headers, and body.
 * @returns {Promise<T>} Parsed response data.
 * @throws {Error} Friendly Portuguese error for HTTP or network failures.
 */
async function request(url, options = {}) {
  try {
    const response = await fetch(url, {
      ...options,
      headers: {
        ...DEFAULT_HEADERS,
        ...(options.headers || {}),
      },
    });

    const data = await parseJsonResponse(response);

    if (!response.ok) {
      throw new Error(buildHttpErrorMessage(response, data || null));
    }

    return data;
  } catch (error) {
    if (error instanceof TypeError) {
      throw new Error(
        "Não foi possível conectar ao DoneFlow. Verifique sua conexão e tente novamente.",
      );
    }

    throw error;
  }
}

/**
 * Create a task and ask DoneFlow to classify it with AI.
 *
 * @param {string} text - Task description typed by the user.
 * @returns {Promise<Task>} Created and classified task.
 * @throws {Error} Friendly Portuguese error when creation or classification fails.
 */
export async function createTask(text) {
  return await request(`${API_BASE_URL}/tasks`, {
    method: "POST",
    body: JSON.stringify({ description: text }),
  });
}

/**
 * Fetch every task persisted in DoneFlow.
 *
 * @returns {Promise<Task[]>} Tasks ordered by the backend default ordering.
 * @throws {Error} Friendly Portuguese error when the list cannot be loaded.
 */
export async function getAllTasks() {
  return await request(`${API_BASE_URL}/tasks`, {
    method: "GET",
  });
}

/**
 * Fetch one task by its UUID.
 *
 * @param {string} id - UUID of the task to retrieve.
 * @returns {Promise<Task>} Matching task.
 * @throws {Error} Friendly Portuguese error when the task cannot be found or loaded.
 */
export async function getTaskById(id) {
  return await request(`${API_BASE_URL}/tasks/${id}`, {
    method: "GET",
  });
}

/**
 * Manually move a task to another Eisenhower Matrix quadrant.
 *
 * @param {string} id - UUID of the task to update.
 * @param {Quadrant} quadrant - New quadrant selected by the user.
 * @returns {Promise<Task>} Updated task.
 * @throws {Error} Friendly Portuguese error when the task cannot be reclassified.
 */
export async function updateTaskQuadrant(id, quadrant) {
  return await request(`${API_BASE_URL}/tasks/${id}`, {
    method: "PATCH",
    body: JSON.stringify({ quadrant }),
  });
}

/**
 * Delete a task from DoneFlow.
 *
 * @param {string} id - UUID of the task to delete.
 * @returns {Promise<void>} Resolves when the task is removed.
 * @throws {Error} Friendly Portuguese error when the task cannot be deleted.
 */
export async function deleteTask(id) {
  await request(`${API_BASE_URL}/tasks/${id}`, {
    method: "DELETE",
  });
}

/**
 * Fetch task counts for each Eisenhower Matrix quadrant.
 *
 * @returns {Promise<Distribution>} Distribution counters for the board summary.
 * @throws {Error} Friendly Portuguese error when distribution data cannot be loaded.
 */
export async function getDistribution() {
  return await request(`${API_BASE_URL}/tasks/distribution`, {
    method: "GET",
  });
}

/**
 * Fetch the DoneFlow API health-check status.
 *
 * @returns {Promise<HealthResponse>} Current health-check payload.
 * @throws {Error} Friendly Portuguese error when the health endpoint cannot be loaded.
 */
export async function getHealth() {
  return await request("/health", {
    method: "GET",
  });
}
